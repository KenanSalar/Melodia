#!/usr/bin/env python3
r"""Regenerates the translation template from the @tr strings in the .slint tree, and merges it.

    python3 scripts/update-translations.py
    py scripts\update-translations.py

Writes `crates/melodia-ui/translations/melodia-ui.pot` and merges it into every catalog beside it.
Run it after adding, changing or removing an @tr string; translating one needs nothing but an
editor.

A note for translators is one `// Translators: ...` line directly above the line holding the @tr,
at most 76 columns from `Translators:` on. Every other comment there is for code readers and stays
out of the catalogs.

Needs slint-tr-extractor at the workspace's slint version, and GNU gettext.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRATE = ROOT / "crates" / "melodia-ui"
TEMPLATE = CRATE / "translations" / "melodia-ui.pot"
TEMPLATE_HEADER = "# Generated by scripts/update-translations.py. Never edit by hand.\n"

GETTEXT_TOOLS = ("msgcat", "msgmerge", "msgattrib", "msgfmt")
INSTALL_GETTEXT = (
    "  Fedora: sudo dnf install gettext",
    "  Debian/Ubuntu: sudo apt install gettext (gettext-base has no msgmerge)",
    "  macOS: brew install gettext",
    "  Windows: winget install mlocati.GetText",
)


class Failure(Exception):
    """Ends the run with its lines on stderr rather than a traceback."""

    def __init__(self, *lines: str) -> None:
        super().__init__("\n".join(lines))
        self.lines = lines


def main() -> int:
    try:
        tools = find_tools()
        with tempfile.TemporaryDirectory(prefix="melodia-translations-") as scratch:
            update(tools, Path(scratch))
    except Failure as failure:
        for line in failure.lines:
            print(f"error: {line}", file=sys.stderr)
        return 1
    return 0


def find_tools() -> dict[str, str]:
    """Every tool the run needs, by name, refusing an extractor that doesn't match the workspace."""
    slint_version = workspace_slint_version()
    install_extractor = f"cargo install slint-tr-extractor --version {slint_version} --locked"

    tools = {}
    extractor = shutil.which("slint-tr-extractor")
    if extractor is None:
        raise Failure("slint-tr-extractor not found. Install it with:", f"  {install_extractor}")
    tools["slint-tr-extractor"] = extractor
    for tool in GETTEXT_TOOLS:
        found = shutil.which(tool)
        if found is None:
            raise Failure(f"{tool} not found. Install GNU gettext:", *INSTALL_GETTEXT)
        tools[tool] = found

    # The extractor parses with the Slint compiler, so it moves with `slint`.
    answer = run_captured([extractor, "--version"])
    extractor_version = answer.split()[1] if len(answer.split()) > 1 else answer.strip()
    if extractor_version != slint_version:
        raise Failure(
            f"slint-tr-extractor is {extractor_version} but the workspace's slint is {slint_version}.",
            f"  {install_extractor}",
        )
    return tools


def workspace_slint_version() -> str:
    manifest = (ROOT / "Cargo.toml").read_text(encoding="utf-8")
    found = re.search(r'^slint = \{ version = "([^"]*)"', manifest, re.MULTILINE)
    if found is None:
        raise Failure("can't read slint's version from Cargo.toml")
    return found.group(1)


def update(tools: dict[str, str], work: Path) -> None:
    extract_parts(tools["slint-tr-extractor"], work)

    run([tools["msgcat"], "--no-wrap", "--sort-by-file", "-o", "merged.pot", *part_names(work)], cwd=work)
    numbered = work / "numbered.pot"
    write_lines(numbered, one_note_per_msgid(read_lines(work / "merged.pot")))

    # msgmerge reads the template with line numbers, which is what lets --sort-by-file follow
    # source order. Against file-only locations it sorts a file's entries alphabetically. The
    # template goes through -o rather than stdout because a Windows gettext writes stdout with CRLF.
    located = work / "template.pot"
    run([tools["msgcat"], "--no-wrap", "--add-location=file", "--sort-by-file", "-o", str(located), str(numbered)])
    with open(TEMPLATE, "w", encoding="utf-8", newline="") as template:
        template.write(TEMPLATE_HEADER)
        template.write(located.read_text(encoding="utf-8"))

    catalogs = sorted(CRATE.glob("translations/*/LC_MESSAGES/melodia-ui.po"))
    for catalog in catalogs:
        run(
            [tools["msgmerge"], "-q", "-U", "--no-wrap", "--add-location=file", "--sort-by-file",
             "--backup=none", str(catalog), str(numbered)]
        )
        run([tools["msgattrib"], "--no-wrap", "--no-obsolete", "-o", str(catalog), str(catalog)])

    # LC_ALL=C keeps the report in English: a Windows gettext otherwise writes it in the system
    # language's code page.
    english = {**os.environ, "LC_ALL": "C"}
    for catalog in catalogs:
        answer = subprocess.run(
            [tools["msgfmt"], "-c", "--statistics", "-o", str(work / "stats.mo"), str(catalog)],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            env=english,
            text=True,
            errors="replace",
        )
        statistics = answer.stdout.strip()
        if answer.returncode != 0:
            raise Failure(statistics)
        language = catalog.relative_to(CRATE / "translations").parts[0]
        print(f"{language}: {statistics}")


def extract_parts(extractor: str, work: Path) -> None:
    """One part per .slint file, its comments down to translator notes.

    One file at a time because rspolib, the extractor's PO writer, drops an occurrence that
    overflows a `#:` line, and a file's first occurrence always fits. The sources are spelled
    relative to the crate with forward slashes, the spelling the template's locations carry.
    """
    sources = sorted(path.relative_to(CRATE).as_posix() for path in (CRATE / "ui").rglob("*.slint"))
    raw = work / "raw.po"
    errors: list[str] = []
    for part, source in enumerate(sources, start=1):
        run([extractor, "--no-default-translation-context", "-o", str(raw), source], cwd=CRATE)
        kept, overlong = keep_translator_notes(read_lines(raw), source)
        errors += overlong
        write_lines(work / f"part-{part:04d}.po", kept)
    if errors:
        raise Failure(*errors)


def keep_translator_notes(lines: list[str], source: str) -> tuple[list[str], list[str]]:
    """The extractor's output with only `Translators:` notes left among an entry's comments.

    The extractor takes whatever `//` line sits above an @tr. This reads the raw text because
    rspolib wraps a comment past 76 columns without its `#.` prefix, which no gettext tool will
    read, so a wrapped note is reported rather than kept. POT-Creation-Date goes too, or every run
    would rewrite the template and every catalog.
    """
    kept: list[str] = []
    errors: list[str] = []
    in_comments = True
    for line in lines:
        if line == "":
            in_comments = True
            kept.append(line)
            continue
        if in_comments and re.match(r"(#:|#,|msgctxt |msgid )", line):
            in_comments = False
        if in_comments:
            if line.startswith("#. Translators:"):
                kept.append(line)
            elif line.startswith("Translators:"):
                errors.append(f"{source}: a translator note runs past 76 columns: {line}")
            continue
        if line.startswith('"POT-Creation-Date: '):
            continue
        kept.append(line)
    return kept, errors


def one_note_per_msgid(lines: list[str]) -> list[str]:
    """msgcat's merge with each translator note once, refusing a msgid that carries two.

    msgcat folds a note into one line only when every file using the msgid carries it, and
    otherwise repeats it per file under a `#-#-#-#-#` marker. A repeat is still one note, so only
    a second, different one fails.
    """
    kept: list[str] = []
    errors: list[str] = []
    seen: set[str] = set()
    for line in lines:
        if line.startswith("#. #-#-#-#-#"):
            continue
        if line == "":
            seen = set()
        if line.startswith("#. Translators:"):
            if line in seen:
                continue
            seen.add(line)
        if line.startswith("msgid ") and len(seen) > 1:
            errors.append(f"{line} has {len(seen)} translator notes, and a msgid gets one")
        kept.append(line)
    if errors:
        raise Failure(*errors)
    return kept


def part_names(work: Path) -> list[str]:
    return sorted(path.name for path in work.glob("part-*.po"))


def read_lines(path: Path) -> list[str]:
    # Iterated rather than splitlines(), which would also split a msgid holding U+2028 or U+0085.
    with open(path, encoding="utf-8") as file:
        return [line.rstrip("\n") for line in file]


def write_lines(path: Path, lines: list[str]) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as file:
        file.write("".join(f"{line}\n" for line in lines))


def run(command: list[str], cwd: Path | None = None) -> None:
    """Runs `command`, its own messages going straight to the terminal."""
    if subprocess.run(command, cwd=cwd, stdin=subprocess.DEVNULL).returncode != 0:
        raise Failure(f"{Path(command[0]).stem} failed: {' '.join(command[1:])}")


def run_captured(command: list[str]) -> str:
    answer = subprocess.run(command, stdin=subprocess.DEVNULL, capture_output=True, text=True, errors="replace")
    if answer.returncode != 0:
        raise Failure(f"{Path(command[0]).stem} failed: {answer.stderr.strip()}")
    return answer.stdout


if __name__ == "__main__":
    sys.exit(main())
